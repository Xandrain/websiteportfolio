export interface Photo {
  src: string;
  alt: string;
}

/**
 * A collection that is a write-up of a role rather than a set of photographs.
 * Its page takes the project-page layout (UPDATING.md §7f) in place of the
 * gallery, and its card on /photography is the Graphic Design & 3D card.
 */
export interface CaseStudy {
  /** Small capitals above the title; the first two are the card's meta line. */
  tags: string[];
  /** The end of `title`, set as a small spaced line under the name. */
  subtitle?: string;
  /** Alt text for `cover` on the card. */
  coverAlt: string;
  /** Square mark shown in a round bubble beside the description. Optional. */
  logo?: Photo;
  /** One fact per row in the card. A fact with `href` links out (new tab). */
  specs: { label: string; value: string; href?: string }[];
  /** The panel beside the facts. */
  about: { heading: string; text: string[] };
  /** A silent looping clip between the facts and the role, made with
   *  `node scripts/gen-video.mjs` (the .webm/.mp4 pair and its -poster.jpg).
   *  `label` names it for the pause button. Optional. */
  loop?: { webm: string; mp4: string; poster: string; label: string };
  /** One block per contribution, each with its image. */
  role: { heading: string; blocks: { title: string; text: string; image: Photo }[] };
  /** The line that closes the card, and its link out. */
  closing: { text: string; label: string; href: string };
  /** Brand colour filling the pills that link out (the linked fact and the
   *  closing button). Text on them stays ink, so pick a light colour. Optional. */
  accent?: string;
}

export interface Collection {
  slug: string;
  title: string;
  description: string;
  cover: string;
  category: string;
  photos: Photo[];
  caseStudy?: CaseStudy;
}

